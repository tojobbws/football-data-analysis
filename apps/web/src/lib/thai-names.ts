type Named = { id: number; name: string };

/** Full Thai name, or the provider name when the team is not listed. */
export const teamTh = (t: Named) => TEAM_TH[t.id]?.th ?? t.name;
/** The name fans type (falls back to the full Thai name, then the provider name). */
export const teamShortTh = (t: Named) => TEAM_TH[t.id]?.short ?? teamTh(t);
/** True when the team has a Thai name, so the provider name is worth showing beside it. */
export const hasTeamTh = (t: Named) => t.id in TEAM_TH;
/** Thai league name, or the provider name when the league is not listed. */
export const leagueTh = (l: Named) => LEAGUE_TH[l.id] ?? l.name;
